M_INIT, M_PROCESS, M_PARAM, M_SHUTDOWN, M_EVENT, M_PAINT, M_GETSTATE, M_SETSTATE, M_RESET, M_TICK = range(1, 11)
R_READY, R_PROCESSED, R_LOG, R_UI, R_PAINT, R_STATE, R_ERROR = range(101, 108)
_HDR = struct.Struct("<II")
_PHDR = struct.Struct("<QII")

try:                                    # optional, only used when a plug-in asks for it
    import numpy as _np
except Exception:                       # pragma: no cover
    _np = None


def _find_plugin_class(mod):
    cls = getattr(mod, "PLUGIN", None)
    if isinstance(cls, type) and issubclass(cls, Plugin):
        return cls
    found = [v for v in vars(mod).values()
             if isinstance(v, type) and issubclass(v, Plugin) and v is not Plugin and v.__module__ == mod.__name__]
    if not found:
        raise RuntimeError("the script defines no class derived from udaw_plugin.Plugin")
    return found[-1]


def load_plugin(source, filename, script_dir=None):
    """Compiles and executes the script; returns (module, plugin instance)."""
    if script_dir and script_dir not in sys.path:
        sys.path.insert(0, script_dir)
    code = compile(source, filename, "exec")
    name = "udaw_user_plugin"
    spec = importlib.util.spec_from_loader(name, loader=None)
    mod = importlib.util.module_from_spec(spec)
    mod.__file__ = filename
    sys.modules[name] = mod
    exec(code, mod.__dict__)
    inst = _find_plugin_class(mod)()
    inst.setup()
    return mod, inst


def build_ui(inst):
    ui = UI(inst._params)
    inst.ui(ui)
    return ui


class _Runtime:
    def __init__(self, rin, rout):
        self.rin, self.rout = rin, rout
        self.wlock = threading.Lock()
        self.inst = None
        self.sr, self.ch, self.maxf = 48000, 2, 512
        self.position = 0
        self.last_flush = 0.0
        self.err_count = 0
        self.faulted = False
        self.out_cache = {}

    # -- wire ------------------------------------------------------------------------------
    def send(self, mtype, payload=b""):
        with self.wlock:
            self.rout.write(_HDR.pack(mtype, len(payload)))
            if payload:
                self.rout.write(payload)
            self.rout.flush()

    def send_json(self, mtype, obj):
        self.send(mtype, json.dumps(obj, separators=(",", ":"), allow_nan=False).encode("utf-8"))

    def log(self, level, text):
        try:
            self.send_json(R_LOG, {"level": level, "text": text})
        except Exception:
            pass

    def error(self, text, fatal=False):
        try:
            self.send_json(R_ERROR, {"text": text, "fatal": fatal})
        except Exception:
            pass

    def read_exact(self, n):
        buf = self.rin.read(n)
        if buf is None or len(buf) < n:
            raise EOFError
        return buf

    # -- ui flush --------------------------------------------------------------------------
    def flush_ui(self, force=False):
        inst = self.inst
        if inst is None:
            return
        now = time.perf_counter()
        if not force and now - self.last_flush < 0.033:
            return
        if inst._ui_params or inst._ui_controls or inst._ui_repaint:
            msg = {"params": inst._ui_params, "controls": inst._ui_controls,
                   "repaint": sorted(inst._ui_repaint)}
            inst._ui_params, inst._ui_controls, inst._ui_repaint = {}, {}, set()
            try:
                self.send_json(R_UI, msg)
            except (TypeError, ValueError) as e:
                self.log("error", "ui_set value is not JSON-serialisable: %s" % e)
        self.last_flush = now

    # -- handlers -------------------------------------------------------------------------
    def on_init(self, d):
        if sys.version_info < MIN_PYTHON:
            raise RuntimeError("UDAW plug-ins need Python %d.%d or newer (this is %d.%d.%d)" %
                               (MIN_PYTHON + sys.version_info[:3]))
        self.sr, self.ch, self.maxf = int(d["sample_rate"]), int(d["channels"]), int(d["max_frames"])
        mod, inst = load_plugin(d["source"], d.get("filename", "plugin.py"), d.get("script_dir"))
        self.inst = inst
        inst.sample_rate, inst.channels, inst.max_frames = self.sr, self.ch, self.maxf
        for pid, v in (d.get("values") or {}).items():
            prm = inst._params._d.get(pid)
            if prm is not None:
                prm.value = prm.clamp(v)
        if d.get("state") is not None:
            inst.set_state(d["state"])
        inst.prepare(self.sr, self.ch, self.maxf)
        ui = build_ui(inst)
        found = []
        _check_overlaps(ui, lambda sev, line, col, msg: found.append((line, msg)))
        _check_sizes(ui, lambda sev, line, col, msg: found.append((line, msg)))
        for line, msg in found:
            self.log("warning", "window layout%s: %s" % (" (script line %d)" % line if line else "", msg))
        self.send_json(R_READY, {
            "name": inst.name, "vendor": inst.vendor, "author": inst.author, "version": inst.version,
            "description": inst.description, "sdk": SDK_VERSION,
            "python": "%d.%d.%d" % sys.version_info[:3],
            "buffered": bool(inst.buffered), "numpy": bool(_np and inst.use_numpy),
            "params": [p.describe() for p in inst._params],
            "ui": ui.to_dict()})

    def on_process(self, payload):
        seq, frames, chans = _PHDR.unpack_from(payload, 0)
        base = _PHDR.size
        inst = self.inst
        n = frames * 4
        use_np = _np is not None and inst.use_numpy
        inp, out = [], []
        for c in range(chans):
            raw = payload[base + c * n: base + (c + 1) * n]
            if use_np:
                a = _np.frombuffer(raw, dtype=_np.float32).copy()
                inp.append(a)
                out.append(a.copy())
            else:
                a = array.array("f")
                a.frombytes(raw)
                inp.append(a)
                out.append(array.array("f", a))
        blk = Block(frames, chans, self.sr, inp, out, self.position)
        self.position += frames
        if not self.faulted:
            try:
                inst.process(blk)
            except Exception:
                self.err_count += 1
                if self.err_count == 1 or self.err_count % 500 == 0:
                    self.error("process() raised (x%d):\n%s" % (self.err_count, traceback.format_exc()))
                blk.copy_through()
        body = bytearray(_PHDR.pack(seq, frames, chans))
        for c in range(chans):
            body += out[c].tobytes()
        self.send(R_PROCESSED, bytes(body))

    def on_param(self, d):
        inst = self.inst
        prm = inst._params._d.get(d["id"])
        if prm is None:
            return
        v = prm.clamp(d["value"])
        prm.value = v
        inst.on_param(prm.id, v)

    def on_event(self, d):
        inst = self.inst
        cid, ev = d.get("id", ""), d.get("event", "")
        if ev.startswith("mouse_") or ev == "wheel" or ev == "double":
            inst.on_mouse(cid, ev[6:] if ev.startswith("mouse_") else ev, d.get("x", 0), d.get("y", 0), d.get("button", 0))
            return
        fn = getattr(inst, "on_" + cid, None)
        if callable(fn):
            fn(ev, d.get("value"))
        else:
            inst.on_event(cid, ev, d.get("value"))

    def on_paint(self, d):
        inst = self.inst
        cv = Canvas(d.get("w", 100), d.get("h", 100))
        cid = d.get("id", "")
        fn = getattr(inst, "paint_" + cid, None)
        if callable(fn):
            fn(cv)
        else:
            inst.paint(cid, cv)
        self.send_json(R_PAINT, {"id": cid, "w": cv.width, "h": cv.height, "cmds": cv.cmds})

    def state_dict(self):
        inst = self.inst
        return {"values": {p.id: p.value for p in inst._params}, "custom": inst.get_state()}

    def run(self):
        while True:
            try:
                mtype, length = _HDR.unpack(self.read_exact(_HDR.size))
                payload = self.read_exact(length) if length else b""
            except EOFError:
                return
            try:
                if mtype == M_PROCESS:
                    self.on_process(payload)
                elif mtype == M_PARAM:
                    self.on_param(json.loads(payload))
                elif mtype == M_INIT:
                    self.on_init(json.loads(payload))
                elif mtype == M_EVENT:
                    self.on_event(json.loads(payload))
                elif mtype == M_PAINT:
                    self.on_paint(json.loads(payload))
                elif mtype == M_TICK:
                    self.inst.on_timer()
                    self.flush_ui(True)
                elif mtype == M_GETSTATE:
                    self.send_json(R_STATE, self.state_dict())
                elif mtype == M_SETSTATE:
                    d = json.loads(payload)
                    for pid, v in (d.get("values") or {}).items():
                        prm = self.inst._params._d.get(pid)
                        if prm is not None:
                            prm.value = prm.clamp(v)
                            self.inst._ui_params[pid] = prm.value
                    if d.get("custom") is not None:
                        self.inst.set_state(d["custom"])
                elif mtype == M_RESET:
                    self.position = 0
                    self.faulted = False
                    self.inst.reset()
                elif mtype == M_SHUTDOWN:
                    return
            except EOFError:
                return
            except Exception:
                fatal = mtype == M_INIT
                self.error(traceback.format_exc(), fatal)
                if fatal:
                    return
            if mtype != M_PROCESS or self.inst is not None:
                try:
                    self.flush_ui()
                except Exception:
                    pass


class _LogWriter(io.TextIOBase):
    """Turns print() / stderr output into log frames the editor shows."""

    def __init__(self, rt, level):
        self.rt, self.level, self.buf = rt, level, ""
        self.window_start, self.count = time.perf_counter(), 0

    def writable(self):
        return True

    def write(self, s):
        self.buf += s
        while "\n" in self.buf:
            line, self.buf = self.buf.split("\n", 1)
            now = time.perf_counter()
            if now - self.window_start > 1.0:
                self.window_start, self.count = now, 0
            self.count += 1
            if self.count <= 200:
                self.rt.log(self.level, line)
        return len(s)

    def flush(self):
        pass


def host_main():
    rin = sys.stdin.buffer
    rout = sys.stdout.buffer
    rt = _Runtime(rin, rout)
    sys.stdout = _LogWriter(rt, "info")
    sys.stderr = _LogWriter(rt, "error")
    rt.run()


