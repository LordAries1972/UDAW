def _script_line():
    """Line of the plug-in script that is creating a control (for validation messages)."""
    f = sys._getframe(1)
    me = f.f_code.co_filename
    while f is not None and f.f_code.co_filename == me:
        f = f.f_back
    return f.f_lineno if f is not None else 0


def _col(c):
    if c is None:
        return None
    if isinstance(c, (tuple, list)):
        return rgb(*c[:3])
    return str(c)


class Canvas:
    """Draw commands for a ``ui.canvas(...)`` control, recorded by ``paint`` and replayed by
    UDAW on its OpenGL canvas.  Origin top-left, pixels, colours "#rrggbb" or (r, g, b).

    Every call is cheap; UDAW asks for a fresh picture about 30 times a second while the
    window is open and the control is visible."""

    def __init__(self, width, height):
        self.width, self.height = int(width), int(height)
        self.cmds = []

    # state ---------------------------------------------------------------------------
    def alpha(self, a):
        """Opacity 0..1 for everything drawn after this call."""
        self.cmds.append(["alpha", float(a)])

    def push_clip(self, x, y, w, h):
        self.cmds.append(["clip", int(x), int(y), int(w), int(h)])

    def pop_clip(self):
        self.cmds.append(["unclip"])

    # fills & shapes ---------------------------------------------------------------------
    def clear(self, color):
        self.fill_rect(0, 0, self.width, self.height, color)

    def fill_rect(self, x, y, w, h, color):
        self.cmds.append(["fr", int(x), int(y), int(w), int(h), _col(color)])

    def rect(self, x, y, w, h, color, width=1):
        self.cmds.append(["sr", int(x), int(y), int(w), int(h), _col(color), int(width)])

    def round_rect(self, x, y, w, h, radius, fill=None, stroke=None, width=1):
        self.cmds.append(["rr", int(x), int(y), int(w), int(h), int(radius), _col(fill), _col(stroke), int(width)])

    def ellipse(self, x, y, w, h, fill=None, stroke=None, width=1):
        self.cmds.append(["el", int(x), int(y), int(w), int(h), _col(fill), _col(stroke), int(width)])

    def circle(self, cx, cy, r, fill=None, stroke=None, width=1):
        self.ellipse(cx - r, cy - r, 2 * r, 2 * r, fill, stroke, width)

    def line(self, x1, y1, x2, y2, color, width=1, dashed=False):
        self.cmds.append(["ln", float(x1), float(y1), float(x2), float(y2), _col(color), int(width), bool(dashed)])

    def polyline(self, points, color, width=1):
        self.cmds.append(["pl", [[round(float(x), 2), round(float(y), 2)] for x, y in points], _col(color), int(width)])

    def polygon(self, points, fill=None, stroke=None, width=1):
        self.cmds.append(["pg", [[round(float(x), 2), round(float(y), 2)] for x, y in points],
                          _col(fill), _col(stroke), int(width)])

    def arc(self, cx, cy, r, start_deg, end_deg, color, width=1, steps=48):
        """Arc from start to end degrees (0 = right, clockwise on screen)."""
        pts = []
        for i in range(steps + 1):
            a = math.radians(start_deg + (end_deg - start_deg) * i / steps)
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
        self.polyline(pts, color, width)

    def gradient(self, x, y, w, h, top, bottom, horizontal=False):
        self.cmds.append(["gr", int(x), int(y), int(w), int(h), _col(top), _col(bottom), bool(horizontal)])

    def plot(self, ys, x=0, y=0, w=None, h=None, lo=-1.0, hi=1.0, color="#6fe0a0", width=1):
        """Plots a list of values as a line scaled into a box (waveforms, curves, spectra)."""
        w = self.width if w is None else w
        h = self.height if h is None else h
        n = len(ys)
        if n < 2:
            return
        span = (hi - lo) or 1.0
        pts = [(x + w * i / (n - 1), y + h - h * (clamp(v, lo, hi) - lo) / span) for i, v in enumerate(ys)]
        self.polyline(pts, color, width)

    def grid(self, x, y, w, h, cols, rows, color="#2a2f38"):
        for i in range(cols + 1):
            xx = x + w * i / cols
            self.line(xx, y, xx, y + h, color)
        for j in range(rows + 1):
            yy = y + h * j / rows
            self.line(x, yy, x + w, yy, color)

    # text -------------------------------------------------------------------------------
    def text(self, x, y, s, color="#dddddd", size=12, bold=False, align="left", width=0):
        """``align`` "left" | "center" | "right" within a box ``width`` px wide starting at x
        (width 0: x is the anchor)."""
        self.cmds.append(["tx", int(x), int(y), str(s), _col(color), int(size), bool(bold), align, int(width)])

    def text_width(self, s, size=12):
        """Rough text width in pixels (UDAW centres/right-aligns exactly when drawing)."""
        return int(len(str(s)) * size * 0.56)


