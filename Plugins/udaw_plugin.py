def db_to_lin(db):
    """Decibels -> linear gain (-120 dB and below is silence)."""
    return 0.0 if db <= -120.0 else 10.0 ** (db / 20.0)


def lin_to_db(lin):
    """Linear gain -> decibels (floored at -120)."""
    return -120.0 if lin <= 1e-6 else 20.0 * math.log10(lin)


def clamp(x, lo, hi):
    return lo if x < lo else hi if x > hi else x


def lerp(a, b, t):
    return a + (b - a) * t


def midi_to_hz(note):
    return 440.0 * 2.0 ** ((note - 69) / 12.0)


def hz_to_midi(hz):
    return 69.0 + 12.0 * math.log2(max(hz, 1e-9) / 440.0)


def rgb(r, g, b):
    """0-255 channels -> "#rrggbb" (every colour argument also accepts a (r, g, b) tuple)."""
    return "#%02x%02x%02x" % (int(clamp(r, 0, 255)), int(clamp(g, 0, 255)), int(clamp(b, 0, 255)))


tanh = math.tanh


def soft_clip(x):
    """Cheap smooth limiter, |result| < 1 (x / (1 + |x|)); faster than tanh in pure Python."""
    return x / (1.0 + (x if x >= 0.0 else -x))


