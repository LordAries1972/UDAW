def _check_lint(tree, issues):
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            fn = node.func
            nm = fn.id if isinstance(fn, ast.Name) else fn.attr if isinstance(fn, ast.Attribute) else ""
            if nm == "input":
                issues.append(("error", node.lineno, node.col_offset, "input() would block the plug-in forever"))
            elif nm == "sleep":
                issues.append(("warning", node.lineno, node.col_offset,
                               "sleep() stalls audio if it runs in process(); avoid it"))
            elif nm in ("system", "Popen", "run") and isinstance(fn, ast.Attribute):
                issues.append(("warning", node.lineno, node.col_offset,
                               "launching programs from a plug-in is almost never what you want"))


_CONTAINERS = ("group", "panel", "recess", "collapse", "scroll_box", "bevel", "shine")


def _rect_of(c):
    """(x, y, w, h) of a control, or None when its size is not known (an unsized label is estimated)."""
    if "w" in c and "h" in c:
        return c["x"], c["y"], c["w"], c["h"]
    if c["type"] == "label":
        txt = str(c.get("props", {}).get("caption", ""))
        size = c.get("props", {}).get("font_size", 9)
        return c["x"], c["y"], int(len(txt) * (size * 0.62) + 2), int(size * 1.7)
    return None


def _inside(a, b, tol=2):
    """True when rectangle a lies entirely within rectangle b."""
    return (a[0] >= b[0] - tol and a[1] >= b[1] - tol and
            a[0] + a[2] <= b[0] + b[2] + tol and a[1] + a[3] <= b[1] + b[3] + tol)


def _check_overlaps(ui, add):
    """Warns about controls that cover each other.  A control lying wholly on a container (group, panel,
    ...) is fine - that is how a frame is used - anything else that intersects is reported by name."""
    by_parent = {}
    for c in ui.controls:
        r = _rect_of(c)
        if r is not None and r[2] > 0 and r[3] > 0:
            by_parent.setdefault(c.get("parent") or "", []).append((c, r))
    for items in by_parent.values():
        for i in range(len(items)):
            for j in range(i + 1, len(items)):
                (a, ra), (b, rb) = items[i], items[j]
                ow = min(ra[0] + ra[2], rb[0] + rb[2]) - max(ra[0], rb[0])
                oh = min(ra[1] + ra[3], rb[1] + rb[3]) - max(ra[1], rb[1])
                if ow < 3 or oh < 3:
                    continue
                a_box, b_box = a["type"] in _CONTAINERS, b["type"] in _CONTAINERS
                if (a_box and _inside(rb, ra)) or (b_box and _inside(ra, rb)):
                    continue
                add("warning", b.get("line", 0), 0,
                    "controls overlap: %r (%s, line %d) and %r (%s, line %d) cover each other by %d x %d px - "
                    "move or resize one of them" % (a["id"], a["type"], a.get("line", 0),
                                                   b["id"], b["type"], b.get("line", 0), ow, oh))


def _check_sizes(ui, add):
    """Controls that are drawn larger than the box they were given (a knob needs room for its dial, value and
    caption) and controls that run past the window."""
    win = ui.win
    for c in ui.controls:
        if "w" not in c or "h" not in c:
            continue
        line = c.get("line", 0)
        if c["type"] == "knob" and c["h"] < c["w"] + 32:
            add("warning", line, 0,
                "knob %r is %d x %d px: its dial, value and caption need a height of at least width + 32 (%d px), "
                "otherwise the caption is covered by whatever sits below it" % (c["id"], c["w"], c["h"], c["w"] + 32))
        if not c.get("parent") and (c["x"] < 0 or c["y"] < 0 or c["x"] + c["w"] > win["width"] or c["y"] + c["h"] > win["height"]):
            add("warning", line, 0, "control %r (%s) extends past the %d x %d px window" %
                (c["id"], c["type"], win["width"], win["height"]))


def validate(path):
    """Returns a list of (severity, line, col, message); severity is error|warning|info."""
    issues = []

    def add(sev, line, col, msg):
        issues.append((sev, line or 0, col or 0, msg))

    if sys.version_info < MIN_PYTHON:
        add("error", 0, 0, "Python %d.%d or newer is required (running %d.%d)" % (MIN_PYTHON + sys.version_info[:2]))
    try:
        with open(path, "r", encoding="utf-8-sig") as f:
            source = f.read()
    except OSError as e:
        add("error", 0, 0, "cannot read the file: %s" % e)
        return issues
    try:
        tree = ast.parse(source, path)
    except SyntaxError as e:
        add("error", e.lineno, e.offset, "syntax error: %s" % e.msg)
        return issues
    _check_lint(tree, issues)
    try:
        mod, inst = load_plugin(source, path, os.path.dirname(os.path.abspath(path)))
    except Exception as e:
        tb = traceback.extract_tb(e.__traceback__)
        line = next((fr.lineno for fr in reversed(tb) if fr.filename == path), 0)
        add("error", line, 0, "%s: %s" % (type(e).__name__, e))
        return issues
    cls = type(inst)
    if cls.name == Plugin.name:
        add("warning", 0, 0, "set a descriptive `name` on the class")
    if cls.process is Plugin.process:
        add("info", 0, 0, "no process() override: the plug-in passes audio through unchanged")
    prms = list(inst._params)
    if not prms:
        add("info", 0, 0, "no parameters declared")
    for p in prms:
        if p.kind in ("float", "int") and not p.min < p.max:
            add("error", 0, 0, "parameter %r: min must be below max" % p.id)
        if not p.min <= p.default <= p.max:
            add("warning", 0, 0, "parameter %r: default %s is outside %s..%s" % (p.id, p.default, p.min, p.max))
        if p.log and p.min <= 0:
            add("error", 0, 0, "parameter %r: logarithmic needs min > 0" % p.id)
    try:
        ui = build_ui(inst)
    except Exception as e:
        add("error", 0, 0, "ui() failed: %s: %s" % (type(e).__name__, e))
        ui = None
    if not (inst.author or "").strip():
        add("warning", 0, 0, "set an `author` on the class so people know who made this plug-in (it is shown in the About box)")
    canvases = []
    if ui is not None:
        _check_overlaps(ui, add)
        _check_sizes(ui, add)
        ids = set()
        win = ui.win
        for c in ui.controls:
            if c["id"] in ids:
                add("error", 0, 0, "duplicate control id %r" % c["id"])
            ids.add(c["id"])
        for c in ui.controls:
            if c.get("param") and c["param"] not in inst._params._d:
                add("error", 0, 0, "control %r is bound to unknown parameter %r" % (c["id"], c["param"]))
            par = c.get("parent") or ""
            if par and par.split("#")[0] not in ids:
                add("error", 0, 0, "control %r has unknown parent %r" % (c["id"], par))
            if c["type"] == "canvas":
                canvases.append(c)
        bound = {c.get("param") for c in ui.controls}
        for p in prms:
            if p.id not in bound:
                add("info", 0, 0, "parameter %r has no control in the window (still automatable)" % p.id)
    # ---- run some audio through it ---------------------------------------------------------
    sr, nch, frames = 48000, 2, 512
    try:
        inst.sample_rate, inst.channels, inst.max_frames = sr, nch, frames
        inst.prepare(sr, nch, frames)
        worst, total = 0.0, 0.0
        silent_all, peak_out = True, 0.0
        use_np = bool(inst.use_numpy and _np is not None)
        if inst.use_numpy and _np is None:
            add("warning", 0, 0, "this plug-in uses numpy, which is not installed here: it will run, but "
                "without its numpy path (pip install numpy)")
        # one silent block first, not timed: the first call of numpy's FFT, caches and lazy set-up would
        # otherwise be reported as if every block were that slow
        warm = [_np.zeros(frames, dtype=_np.float32) if use_np else array.array("f", bytes(4 * frames))
                for _ in range(nch)]
        inst.process(Block(frames, nch, sr, warm, [w.copy() if use_np else array.array("f", w) for w in warm], 0))
        inst.reset()
        for b in range(8):
            ch_in = []
            for c in range(nch):
                a = array.array("f")
                for i in range(frames):
                    t = (b * frames + i) / sr
                    a.append(0.4 * math.sin(2 * math.pi * 196.0 * t) * (1.0 if i % 997 else 0.5)
                             + 0.05 * math.sin(2 * math.pi * 3100.0 * t))
                ch_in.append(_np.array(a, dtype=_np.float32) if use_np else a)
            blk = Block(frames, nch, sr, ch_in,
                        [a.copy() if use_np else array.array("f", a) for a in ch_in], b * frames)
            t0 = time.perf_counter()
            inst.process(blk)
            dt = time.perf_counter() - t0
            worst = max(worst, dt)
            total += dt
            for c in range(nch):
                if len(blk.out[c]) != frames:
                    add("error", 0, 0, "process() changed the length of out[%d]" % c)
                    raise StopIteration
                for v in blk.out[c]:
                    if v != v or v in (math.inf, -math.inf):
                        add("error", 0, 0, "process() produced NaN / infinity")
                        raise StopIteration
                    if v != 0.0:
                        silent_all = False
                    av = -v if v < 0 else v
                    if av > peak_out:
                        peak_out = av
        budget = frames / sr
        load = 100.0 * (total / 8) / budget
        add("info", 0, 0, "test audio: average %.1f%% of real time (worst block %.1f%%), output peak %.2f"
            % (load, 100.0 * worst / budget, peak_out))
        if worst > budget:
            add("error" if total / 8 > budget else "warning", 0, 0,
                "too slow for real-time (a %d-sample block takes longer than the %.1f ms it represents): "
                "simplify the loop, set `buffered = True`, or vectorise with `use_numpy = True`" % (frames, budget * 1000))
        elif load > 50:
            add("warning", 0, 0, "uses over half the real-time budget; several instances may not keep up")
        if silent_all:
            add("warning", 0, 0, "the plug-in output silence for a loud test signal")
        if peak_out > 8.0:
            add("warning", 0, 0, "output peak %.1f is extremely loud; check your gain staging" % peak_out)
    except StopIteration:
        pass
    except Exception as e:
        tb = traceback.extract_tb(e.__traceback__)
        line = next((fr.lineno for fr in reversed(tb) if fr.filename == path), 0)
        add("error", line, 0, "process() raised %s: %s" % (type(e).__name__, e))
    for c in canvases:
        try:
            cv = Canvas(c.get("w", 100), c.get("h", 100))
            fn = getattr(inst, "paint_" + c["id"], None)
            fn(cv) if callable(fn) else inst.paint(c["id"], cv)
            json.dumps(cv.cmds, allow_nan=False)
        except Exception as e:
            tb = traceback.extract_tb(e.__traceback__)
            line = next((fr.lineno for fr in reversed(tb) if fr.filename == path), 0)
            add("error", line, 0, "paint for canvas %r raised %s: %s" % (c["id"], type(e).__name__, e))
    try:
        json.dumps(inst.get_state(), allow_nan=False)
        inst.set_state(json.loads(json.dumps(inst.get_state())))
    except Exception as e:
        add("error", 0, 0, "get_state()/set_state() must round-trip JSON data: %s" % e)
    if not any(s == "error" for s, *_ in issues):
        add("info", 0, 0, "OK - %d parameter(s), %d control(s)" % (len(prms), len(ui.controls) if ui else 0))
    return issues


def main(argv):
    if len(argv) >= 3 and argv[1] == "--validate":
        res = validate(argv[2])
        sys.stdout.write(json.dumps([{"severity": s, "line": l, "col": c, "message": m} for s, l, c, m in res]))
        return 1 if any(s == "error" for s, *_ in res) else 0
    if len(argv) >= 2 and argv[1] == "--host":
        host_main()
        return 0
    print(__doc__)
    return 0


if __name__ == "__main__":
    # a plug-in's `import udaw_plugin` must resolve to this very module, not a second copy
    sys.modules["udaw_plugin"] = sys.modules[__name__]
    sys.exit(main(sys.argv))
