class UI:
    """Describes the plug-in window.  Called once from ``Plugin.ui(self, ui)``.

    Every method takes the control's *id* first, then position and size in pixels
    (``x, y, w, h``) relative to its ``parent`` (the window by default).  A control bound
    with ``param="id"`` follows that parameter in both directions, picks up its range,
    default, logarithmic scale and unit, takes part in automation and is saved with the
    project.  Extra keyword arguments are passed straight to the control's property of the
    same name (``Decimals=1``, ``font_size=14`` ...), so every property of UDAW's controls
    is reachable.

    Control types
    -------------
    label, button, check, knob, slider, eq_slider, meter, progress, combo, list, edit, memo,
    group, panel, recess, collapse, tabs (pages; parent "id#n"), tab_strip, scroll_bar,
    scroll_box, list_view, tree, bevel, shine, splitter, status, canvas (your own drawing).
    """

    #: a control that lies wholly on one of these becomes its child (see ``add``)
    _FRAMES = ("group", "panel", "recess")

    def __init__(self, params):
        self._params = params
        self.controls = []
        self.win = {"width": 480, "height": 320, "title": "", "color": None}
        self._ids = set()
        self._frames = []        # (id, parent, x, y, w, h) of the frames placed so far, as the script gave them

    # window ------------------------------------------------------------------------------
    def window(self, width=480, height=320, title="", color=None):
        self.win = {"width": int(width), "height": int(height), "title": str(title), "color": _col(color)}

    # generic ----------------------------------------------------------------------------
    def add(self, ctype, cid, x=0, y=0, w=None, h=None, parent=None, **kw):
        """Adds any control by type name; the typed helpers below call this."""
        ctl = {"type": ctype, "id": str(cid), "x": int(x), "y": int(y), "parent": parent or "",
               "line": _script_line()}
        if w is not None:
            ctl["w"] = int(w)
        if h is not None:
            ctl["h"] = int(h)
        for k in ("param", "label"):
            if kw.get(k) is not None:
                ctl[k] = kw.pop(k)
            else:
                kw.pop(k, None)
        for k in list(kw):
            v = kw[k]
            if k.lower() in ("color", "font_color", "head_color", "corner_color") and v is not None:
                kw[k] = _col(v)
        ctl["props"] = kw
        # A control placed wholly on a group / panel belongs to it: it is created inside the frame, so it
        # takes the frame's background instead of painting the page colour over it, and it moves and
        # scales with the frame.  Coordinates stay as written in the script (relative to the frame's parent).
        if w is not None and h is not None:
            rect = (int(x), int(y), int(w), int(h))
            for fid, fpar, fx, fy, fw, fh in reversed(self._frames):
                if fpar == (parent or "") and fid != str(cid) and \
                        rect[0] >= fx and rect[1] >= fy and rect[0] + rect[2] <= fx + fw and rect[1] + rect[3] <= fy + fh:
                    ctl["parent"] = fid
                    ctl["x"], ctl["y"] = rect[0] - fx, rect[1] - fy
                    break
            if ctype in self._FRAMES:
                self._frames.append((str(cid), parent or "", rect[0], rect[1], rect[2], rect[3]))
        self.controls.append(ctl)
        return str(cid)

    def label(self, cid, text, x, y, w=None, h=None, **kw):
        return self.add("label", cid, x, y, w, h, caption=text, **kw)

    def button(self, cid, text, x, y, w=80, h=26, toggle=False, param=None, **kw):
        return self.add("button", cid, x, y, w, h, caption=text, toggle=toggle, param=param, **kw)

    def check(self, cid, text, x, y, w=120, h=22, param=None, **kw):
        return self.add("check", cid, x, y, w, h, caption=text, param=param, **kw)

    def knob(self, cid, x, y, w=64, h=84, param=None, label=None, **kw):
        return self.add("knob", cid, x, y, w, h, param=param, caption=label if label is not None else "", **kw)

    def slider(self, cid, x, y, w=160, h=28, param=None, vertical=False, **kw):
        return self.add("slider", cid, x, y, w, h, param=param, vertical=vertical, **kw)

    def eq_slider(self, cid, x, y, w=28, h=160, param=None, **kw):
        return self.add("eq_slider", cid, x, y, w, h, param=param, **kw)

    def meter(self, cid, x, y, w=12, h=100, vertical=True, min=0.0, max=1.0, **kw):
        """Level bar; drive it with ``self.ui_set(cid, value=level)``."""
        return self.add("meter", cid, x, y, w, h, vertical=vertical, min=min, max=max, **kw)

    progress = meter

