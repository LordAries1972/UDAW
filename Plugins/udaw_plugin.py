"""UDAW Python plug-in SDK  (requires Python 3.14 or newer, standard library only).

A UDAW plug-in is an ordinary Python file that defines one class derived from
``udaw_plugin.Plugin``.  UDAW runs it as an audio effect on any Timeline lane or
Tracker channel, draws the window it describes with UDAW's own controls, and keeps the
plug-in's settings inside the project.

Minimal example::

    import udaw_plugin as up

    class Plugin(up.Plugin):
        name = "Gain"

        def setup(self):
            self.add_param("gain", "Gain", min=-24, max=24, default=0, unit="dB")

        def process(self, block):
            g = up.db_to_lin(self.p.gain)
            for ch in range(block.channels):
                src, dst = block.inp[ch], block.out[ch]
                for i in range(block.frames):
                    dst[i] = src[i] * g

Everything below the line "Public API" is what plug-in authors use.  The part after
"Host runtime" is UDAW's side of the conversation and should not be edited.

This file is regenerated by UDAW whenever it starts; keep your own plug-ins in other files.
"""

