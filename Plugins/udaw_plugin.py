class Biquad:
    """RBJ biquad.  ``Biquad("lowpass", sr, 1000, 0.707)`` then ``y = f.tick(x)``.

    Kinds: lowpass, highpass, bandpass, notch, peak, lowshelf, highshelf, allpass.
    ``gain_db`` is used by peak / shelves."""

    def __init__(self, kind="lowpass", sample_rate=48000.0, freq=1000.0, q=0.7071, gain_db=0.0):
        self.kind, self.sr = kind, float(sample_rate)
        self.z1 = self.z2 = 0.0
        self.set(freq, q, gain_db)

    def set(self, freq, q=0.7071, gain_db=0.0, kind=None):
        if kind:
            self.kind = kind
        freq = clamp(freq, 10.0, self.sr * 0.49)
        q = max(q, 0.05)
        w0 = 2.0 * math.pi * freq / self.sr
        cw, sw = math.cos(w0), math.sin(w0)
        alpha = sw / (2.0 * q)
        a = 10.0 ** (gain_db / 40.0)
        k = self.kind
        if k == "lowpass":
            b0, b1, b2 = (1 - cw) / 2, 1 - cw, (1 - cw) / 2
            a0, a1, a2 = 1 + alpha, -2 * cw, 1 - alpha
        elif k == "highpass":
            b0, b1, b2 = (1 + cw) / 2, -(1 + cw), (1 + cw) / 2
            a0, a1, a2 = 1 + alpha, -2 * cw, 1 - alpha
        elif k == "bandpass":
            b0, b1, b2 = alpha, 0.0, -alpha
            a0, a1, a2 = 1 + alpha, -2 * cw, 1 - alpha
        elif k == "notch":
            b0, b1, b2 = 1.0, -2 * cw, 1.0
            a0, a1, a2 = 1 + alpha, -2 * cw, 1 - alpha
        elif k == "peak":
            b0, b1, b2 = 1 + alpha * a, -2 * cw, 1 - alpha * a
            a0, a1, a2 = 1 + alpha / a, -2 * cw, 1 - alpha / a
        elif k == "allpass":
            b0, b1, b2 = 1 - alpha, -2 * cw, 1 + alpha
            a0, a1, a2 = 1 + alpha, -2 * cw, 1 - alpha
        elif k in ("lowshelf", "highshelf"):
            sq = 2.0 * math.sqrt(a) * alpha
            if k == "lowshelf":
                b0 = a * ((a + 1) - (a - 1) * cw + sq)
                b1 = 2 * a * ((a - 1) - (a + 1) * cw)
                b2 = a * ((a + 1) - (a - 1) * cw - sq)
                a0 = (a + 1) + (a - 1) * cw + sq
                a1 = -2 * ((a - 1) + (a + 1) * cw)
                a2 = (a + 1) + (a - 1) * cw - sq
            else:
                b0 = a * ((a + 1) + (a - 1) * cw + sq)
                b1 = -2 * a * ((a - 1) + (a + 1) * cw)
                b2 = a * ((a + 1) + (a - 1) * cw - sq)
                a0 = (a + 1) - (a - 1) * cw + sq
                a1 = 2 * ((a - 1) - (a + 1) * cw)
                a2 = (a + 1) - (a - 1) * cw - sq
        else:
            raise ValueError("unknown biquad kind: " + str(k))
        self.b0, self.b1, self.b2 = b0 / a0, b1 / a0, b2 / a0
        self.a1, self.a2 = a1 / a0, a2 / a0

    def tick(self, x):
        y = self.b0 * x + self.z1
        self.z1 = self.b1 * x - self.a1 * y + self.z2
        self.z2 = self.b2 * x - self.a2 * y
        return y

    def reset(self):
        self.z1 = self.z2 = 0.0


class OnePole:
    """One-pole filter: ``OnePole(sr, freq, "lowpass"|"highpass")``; ``y = f.tick(x)``."""

    def __init__(self, sample_rate=48000.0, freq=1000.0, kind="lowpass"):
        self.sr, self.kind, self.z = float(sample_rate), kind, 0.0
        self.set(freq)

    def set(self, freq):
        self.a = 1.0 - math.exp(-2.0 * math.pi * clamp(freq, 1.0, self.sr * 0.49) / self.sr)

    def tick(self, x):
        self.z += self.a * (x - self.z)
        return self.z if self.kind == "lowpass" else x - self.z

    def reset(self):
        self.z = 0.0


class DCBlocker:
    """Removes DC offset (asymmetric distortion creates plenty)."""

    def __init__(self, sample_rate=48000.0, freq=15.0):
        self.r = 1.0 - 2.0 * math.pi * freq / float(sample_rate)
        self.x1 = self.y1 = 0.0

    def tick(self, x):
        y = x - self.x1 + self.r * self.y1
        self.x1, self.y1 = x, y
        return y

    def reset(self):
        self.x1 = self.y1 = 0.0


class Smoother:
    """Glides a value to its target to avoid zipper noise: ``s.target = v`` ... ``s.tick()``."""

    def __init__(self, value=0.0, sample_rate=48000.0, ms=15.0):
        self.value = self.target = float(value)
        self.set_time(sample_rate, ms)

    def set_time(self, sample_rate, ms):
        self.coef = 1.0 - math.exp(-1.0 / max(1.0, 0.001 * ms * sample_rate))

    def tick(self):
        self.value += self.coef * (self.target - self.value)
        return self.value

    def jump(self, v):
        self.value = self.target = float(v)


class EnvelopeFollower:
    """Peak envelope with separate attack / release (milliseconds)."""

    def __init__(self, sample_rate=48000.0, attack_ms=5.0, release_ms=120.0):
        self.sr, self.env = float(sample_rate), 0.0
        self.set(attack_ms, release_ms)

    def set(self, attack_ms, release_ms):
        self.ca = math.exp(-1.0 / max(1.0, 0.001 * attack_ms * self.sr))
        self.cr = math.exp(-1.0 / max(1.0, 0.001 * release_ms * self.sr))

    def tick(self, x):
        x = -x if x < 0 else x
        c = self.ca if x > self.env else self.cr
        self.env = c * self.env + (1.0 - c) * x
        return self.env


class DelayLine:
    """Circular delay with linear interpolation: ``d.write(x)`` then ``d.read(samples)``."""

    def __init__(self, max_samples):
        self.n = int(max_samples) + 2
        self.buf = [0.0] * self.n
        self.pos = 0

    def write(self, x):
        self.buf[self.pos] = x
        self.pos = (self.pos + 1) % self.n

    def read(self, delay):
        d = clamp(delay, 0.0, self.n - 2)
        i = int(d)
        f = d - i
        a = self.buf[(self.pos - 1 - i) % self.n]
        b = self.buf[(self.pos - 2 - i) % self.n]
        return a + (b - a) * f


class LFO:
    """Sine / triangle / saw / square LFO: ``LFO(sr, hz, "sine")``; ``v = l.tick()`` is -1..1."""

    def __init__(self, sample_rate=48000.0, freq=1.0, shape="sine"):
        self.sr, self.freq, self.shape, self.ph = float(sample_rate), freq, shape, 0.0

    def tick(self):
        p = self.ph
        self.ph = (p + self.freq / self.sr) % 1.0
        s = self.shape
        if s == "sine":
            return math.sin(2.0 * math.pi * p)
        if s == "triangle":
            return 4.0 * abs(p - 0.5) - 1.0
        if s == "saw":
            return 2.0 * p - 1.0
        return 1.0 if p < 0.5 else -1.0


