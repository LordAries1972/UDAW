class Param:
    """One automatable setting.  kind: "float" (default), "int", "bool" or "choice"."""

    def __init__(self, pid, name, min=0.0, max=1.0, default=0.0, unit="", kind="float",
                 choices=None, log=False, step=0.0, decimals=None, group=""):
        self.id, self.name, self.unit, self.group = str(pid), str(name), str(unit), str(group)
        self.kind = kind
        self.choices = list(choices) if choices else []
        if kind == "choice":
            min, max = 0, builtins.max(0, len(self.choices) - 1)
        elif kind == "bool":
            min, max = 0, 1
        self.min, self.max, self.default = float(min), float(max), float(default)
        self.log, self.step = bool(log), float(step)
        self.decimals = decimals if decimals is not None else (0 if kind in ("int", "bool", "choice") else 2)
        self.value = self.default

    def clamp(self, v):
        v = float(v)
        if v != v:                      # NaN
            v = self.default
        v = clamp(v, self.min, self.max)
        if self.kind in ("int", "bool", "choice"):
            v = float(round(v))
        elif self.step > 0:
            v = self.min + round((v - self.min) / self.step) * self.step
        return v

    def describe(self):
        return {"id": self.id, "name": self.name, "min": self.min, "max": self.max,
                "default": self.default, "value": self.value, "unit": self.unit,
                "kind": self.kind, "choices": self.choices, "log": self.log,
                "step": self.step, "decimals": self.decimals, "group": self.group}


class _Params:
    """``self.p.drive`` / ``self.p["drive"]`` -> current value (bool params give a bool,
    choice params the chosen index)."""

    def __init__(self):
        object.__setattr__(self, "_d", {})

    def _add(self, prm):
        self._d[prm.id] = prm

    def __getattr__(self, k):
        try:
            prm = self._d[k]
        except KeyError:
            raise AttributeError("no parameter named %r (declared: %s)" % (k, ", ".join(self._d))) from None
        return bool(prm.value) if prm.kind == "bool" else (int(prm.value) if prm.kind in ("int", "choice") else prm.value)

    __getitem__ = __getattr__

    def __iter__(self):
        return iter(self._d.values())


# ---- audio block ------------------------------------------------------------------------

class Block:
    """One buffer of audio.

    ``inp[ch]`` and ``out[ch]`` are ``array.array('f')`` (or numpy float32 arrays when the
    plug-in sets ``use_numpy = True`` and numpy is installed), ``frames`` long.  ``out``
    starts as a copy of ``inp``, so a plug-in that does not write a channel passes it
    through unchanged."""

    __slots__ = ("frames", "channels", "sample_rate", "inp", "out", "position")

    def __init__(self, frames, channels, sample_rate, inp, out, position):
        self.frames, self.channels, self.sample_rate = frames, channels, sample_rate
        self.inp, self.out, self.position = inp, out, position

    def peak(self, ch=None):
        """Largest absolute input sample (all channels, or just ``ch``)."""
        chans = range(self.channels) if ch is None else (ch,)
        m = 0.0
        for c in chans:
            for v in self.inp[c]:
                v = -v if v < 0 else v
                if v > m:
                    m = v
        return m

    def copy_through(self):
        for c in range(self.channels):
            self.out[c][:] = self.inp[c]


